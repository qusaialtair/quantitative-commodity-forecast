@st.cache_data(ttl=3600, show_spinner=False)
def get_tri_horizon_predictions(ticker: str, current_price: float) -> dict:
    """
    Load all 3 proving-ground models for a ticker and return predicted prices.
    Returns {'tactical': float, 'strategic': float, 'structural': float} or error dict.
    """
    import torch, joblib, numpy as np, pandas as pd
    from pathlib import Path as _P

    MODELS_DIR = ROOT / "models" / "proving_ground"
    tag        = ticker.replace("=", "").replace("^", "")
    csv_path   = ROOT / "data" / f"{ticker}_8yr_macro.csv"

    if not csv_path.exists():
        return {"error": "harvest_needed"}

    df = pd.read_csv(csv_path, index_col=0, parse_dates=True)
    features = ["Close_Price", "Volume", "DXY_Close", "VIX_Close"]
    results  = {}

    for horizon in ["tactical", "strategic", "structural"]:
        pth_path    = MODELS_DIR / f"{tag}_{horizon}.pth"
        scaler_path = MODELS_DIR / f"{tag}_{horizon}_scaler.pkl"
        if not pth_path.exists() or not scaler_path.exists():
            results[horizon] = None
            continue
        try:
            checkpoint = torch.load(pth_path, map_location="cpu", weights_only=False)
            seq_len    = checkpoint["seq_len"]
            hidden     = checkpoint.get("hidden_size", 128)
            layers     = checkpoint.get("num_layers",  2)
            inp_size   = checkpoint.get("input_size",  4)

            class _LSTM(torch.nn.Module):
                def __init__(self):
                    super().__init__()
                    self.lstm = torch.nn.LSTM(inp_size, hidden, layers,
                                              batch_first=True, dropout=0.2)
                    self.head = torch.nn.Sequential(
                        torch.nn.Linear(hidden, 64), torch.nn.ReLU(),
                        torch.nn.Linear(64, 1))
                def forward(self, x):
                    out, _ = self.lstm(x)
                    return self.head(out[:, -1, :]).squeeze(-1)

            model = _LSTM()
            model.load_state_dict(checkpoint["model_state"])
            model.eval()

            scaler  = joblib.load(scaler_path)
            raw     = df[features].values[-seq_len:]
            if len(raw) < seq_len:
                results[horizon] = None
                continue

            scaled  = scaler.transform(raw)
            x       = torch.tensor(scaled, dtype=torch.float32).unsqueeze(0)
            with torch.no_grad():
                pred_scaled = model(x).item()

            # Inverse-transform: only Close_Price (col 0)
            dummy = np.zeros((1, len(features)))
            dummy[0, 0] = pred_scaled
            pred_price  = scaler.inverse_transform(dummy)[0, 0]
            results[horizon] = float(pred_price)
        except Exception as exc:
            results[horizon] = None

    return results


