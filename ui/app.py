def rsi(series, period=14):
    d  = series.diff()
    up = d.clip(lower=0).ewm(com=period - 1, min_periods=period).mean()
    dn = (-d.clip(upper=0)).ewm(com=period - 1, min_periods=period).mean()
    return 100 - 100 / (1 + up / dn.replace(0, float("nan")))

def _safe(val, fallback=0.0):
    v = float(val) if not (isinstance(val, float) and np.isnan(val)) else fallback
    return v if np.isfinite(v) else fallback

def _clamp(v, lo=-1.0, hi=1.0):
    return max(lo, min(hi, v))

def signal_engine(df, perp):
    empty = dict(signal="HOLD", css="hold", conf=50, color="#f59e0b",
                 cur=0, ma50=0, ma200=0, rsi_val=50, ret1=0, ret5=0,
                 ret21=0, ret63=0, vol21=0, combined=0, hi52=0, lo52=0)
    if df.empty or len(df) < 50:
        return empty

    n = len(df)
    cl = df["Close"]
    hi_s = df["High"] if "High" in df.columns else cl
    lo_s = df["Low"] if "Low" in df.columns else cl
    vol_s = df["Volume"] if "Volume" in df.columns else pd.Series(0, index=df.index)

    cur = _safe(cl.iloc[-1])
    if cur == 0:
        return empty

    ma10  = _safe(cl.rolling(10).mean().iloc[-1], cur)
    ma20  = _safe(cl.rolling(20).mean().iloc[-1], cur)
    ma50  = _safe(cl.rolling(50).mean().iloc[-1], cur)
    ma200 = _safe(cl.rolling(200).mean().iloc[-1], cur) if n >= 200 else ma50

    rsi_v  = _safe(rsi(cl, 14).iloc[-1], 50)
    rsi_7  = _safe(rsi(cl, 7).iloc[-1], 50)
    rsi_21 = _safe(rsi(cl, 21).iloc[-1], 50)

    ema12 = cl.ewm(span=12, min_periods=12).mean()
    ema26 = cl.ewm(span=26, min_periods=20).mean()
    macd_line = ema12 - ema26
    macd_sig  = macd_line.ewm(span=9, min_periods=5).mean()
    macd_hist_series = macd_line - macd_sig
    macd_hist = _safe(macd_hist_series.iloc[-1])
    macd_hist_prev = _safe(macd_hist_series.iloc[-2]) if n > 1 else 0.0

    pct = cl.pct_change()
    ret1  = _safe(pct.iloc[-1] * 100)
    ret5  = _safe(cl.pct_change(5).iloc[-1]  * 100)
    ret21 = _safe(cl.pct_change(21).iloc[-1] * 100)
    ret63 = _safe(cl.pct_change(63).iloc[-1] * 100) if n >= 63 else 0.0
    vol21 = _safe(pct.rolling(21).std().iloc[-1] * 100, 1.0)
    hi52  = _safe(cl.rolling(min(252, n)).max().iloc[-1], cur)
    lo52  = _safe(cl.rolling(min(252, n)).min().iloc[-1], cur)
    range_pos = (cur - lo52) / (hi52 - lo52) if hi52 > lo52 else 0.5

    # --- Bollinger Bands (20, 2sigma) ---
    bb_mid = cl.rolling(20).mean()
    bb_std = cl.rolling(20).std()
    bb_upper = bb_mid + 2 * bb_std
    bb_lower = bb_mid - 2 * bb_std
    bb_mid_v = _safe(bb_mid.iloc[-1], cur)
    bb_upper_v = _safe(bb_upper.iloc[-1], cur * 1.02)
    bb_lower_v = _safe(bb_lower.iloc[-1], cur * 0.98)
    bb_width = (bb_upper_v - bb_lower_v) / bb_mid_v if bb_mid_v > 0 else 0.04
    pct_b = (cur - bb_lower_v) / (bb_upper_v - bb_lower_v) if (bb_upper_v - bb_lower_v) > 0 else 0.5
    bb_width_20 = ((bb_upper - bb_lower) / bb_mid).rolling(min(50, n)).mean()
    bb_width_avg = _safe(bb_width_20.iloc[-1], bb_width)
    squeeze = bb_width < bb_width_avg * 0.75

    # --- On-Balance Volume & VWAP ---
    vol_f = vol_s.astype(float)
    has_volume = vol_f.sum() > 0
    if has_volume:
        obv = (np.sign(pct.fillna(0)) * vol_f).cumsum()
        obv_anchor = max(1, abs(_safe(obv.iloc[-min(10, n)])))
        obv_slope = _safe((obv.iloc[-1] - obv.iloc[-min(10, n)]) / obv_anchor)
        obv_trend = _clamp(obv_slope * 5)

        tp = (hi_s + lo_s + cl) / 3
        vwap_cum_pv = (tp * vol_f).rolling(20).sum()
        vwap_cum_v  = vol_f.rolling(20).sum()
        vwap_20 = vwap_cum_pv / vwap_cum_v.replace(0, np.nan)
        vwap_v = _safe(vwap_20.iloc[-1], cur)
        vwap_score = _clamp((cur - vwap_v) / (cur * 0.01)) if cur > 0 else 0.0

        vol_sma20 = vol_f.rolling(20).mean()
        vol_sma20_v = _safe(vol_sma20.iloc[-1])
        vol_ratio = _safe(vol_f.iloc[-1] / vol_sma20_v, 1.0) if vol_sma20_v > 0 else 1.0
        vol_confirm = _clamp((vol_ratio - 1.0) * np.sign(ret1))
    else:
        obv_trend, vwap_score, vol_confirm = 0.0, 0.0, 0.0

    # --- Ichimoku Cloud ---
    tenkan_p, kijun_p = min(9, n), min(26, n)
    tenkan = (hi_s.rolling(tenkan_p).max() + lo_s.rolling(tenkan_p).min()) / 2
    kijun  = (hi_s.rolling(kijun_p).max() + lo_s.rolling(kijun_p).min()) / 2
    senkou_a = (tenkan + kijun) / 2
    senkou_b_p = min(52, n)
    senkou_b = (hi_s.rolling(senkou_b_p).max() + lo_s.rolling(senkou_b_p).min()) / 2

    tenkan_v   = _safe(tenkan.iloc[-1], cur)
    kijun_v    = _safe(kijun.iloc[-1], cur)
    senkou_a_v = _safe(senkou_a.iloc[-1], cur)
    senkou_b_v = _safe(senkou_b.iloc[-1], cur)
    cloud_top    = max(senkou_a_v, senkou_b_v)
    cloud_bottom = min(senkou_a_v, senkou_b_v)

    if cur > cloud_top:
        ichi_pos = _clamp((cur - cloud_top) / (cur * 0.02))
    elif cur < cloud_bottom:
        ichi_pos = _clamp((cur - cloud_bottom) / (cur * 0.02))
    else:
        ichi_pos = _clamp((cur - cloud_bottom) / max(cloud_top - cloud_bottom, 0.01) * 2 - 1)

    tk_cross = _clamp((tenkan_v - kijun_v) / (cur * 0.005)) if cur > 0 else 0.0
    cloud_bull = 1.0 if senkou_a_v > senkou_b_v else -1.0

    # --- Multi-period Rate of Change ---
    def roc(period):
        if n < period + 1:
            return 0.0
        prev = _safe(cl.iloc[-period - 1], cur)
        return ((cur - prev) / prev * 100) if prev > 0 else 0.0

    roc5, roc10, roc21 = roc(5), roc(10), roc(21)
    roc63 = roc(63) if n >= 64 else 0.0

    # --- Momentum divergence ---
    lookback = min(63, n - 1)
    price_window = cl.iloc[-lookback:]
    rsi_window   = rsi(cl, 14).iloc[-lookback:]
    price_at_high = _safe(price_window.max())
    recent = min(10, lookback)

    price_near_high = cur >= price_at_high * 0.995
    rsi_declining = _safe(rsi_window.iloc[-1], 50) < _safe(rsi_window.iloc[-recent:].max(), 50) - 5
    bearish_div = price_near_high and rsi_declining

    price_at_low = _safe(price_window.min())
    price_near_low = cur <= price_at_low * 1.005
    rsi_rising = _safe(rsi_window.iloc[-1], 50) > _safe(rsi_window.iloc[-recent:].min(), 50) + 5
    bullish_div = price_near_low and rsi_rising

    div_score = -0.6 if bearish_div else (0.6 if bullish_div else 0.0)

    # --- ADX / Directional Index ---
    if n >= 15:
        tr1 = hi_s - lo_s
        tr2 = (hi_s - cl.shift(1)).abs()
        tr3 = (lo_s - cl.shift(1)).abs()
        tr = pd.concat([tr1, tr2, tr3], axis=1).max(axis=1)
        atr14 = tr.rolling(14).mean()

        dm_plus  = (hi_s - hi_s.shift(1)).clip(lower=0)
        dm_minus = (lo_s.shift(1) - lo_s).clip(lower=0)
        dm_plus  = dm_plus.where(dm_plus > dm_minus, 0)
        dm_minus = dm_minus.where(dm_minus > dm_plus, 0)

        di_plus  = 100 * dm_plus.rolling(14).mean() / atr14.replace(0, np.nan)
        di_minus = 100 * dm_minus.rolling(14).mean() / atr14.replace(0, np.nan)
        dx = 100 * (di_plus - di_minus).abs() / (di_plus + di_minus).replace(0, np.nan)
        adx = _safe(dx.rolling(14).mean().iloc[-1], 20)
        di_diff = _safe(di_plus.iloc[-1], 0) - _safe(di_minus.iloc[-1], 0)
    else:
        adx, di_diff = 20.0, 0.0

    trend_strength = _clamp(adx / 40)
    di_score = _clamp(di_diff / 30)

    # =========================================================================
    # 20+ continuous factors, each in [-1, +1], with base weights
    # =========================================================================
    def ma_factor(price, ma_val):
        return _clamp((price - ma_val) / (ma_val * 0.02)) if ma_val > 0 else 0.0

    factors = {}
    factors["ma10"]         = (1.5, ma_factor(cur, ma10))
    factors["ma20"]         = (1.5, ma_factor(cur, ma20))
    factors["ma50"]         = (2.0, ma_factor(cur, ma50))
    factors["ma200"]        = (2.5, ma_factor(cur, ma200))
    factors["ma_short_med"] = (1.5, _clamp((ma10 - ma50) / (ma50 * 0.01)) if ma50 > 0 else 0.0)
    factors["golden_cross"] = (2.0, _clamp((ma50 - ma200) / (ma200 * 0.01)) if ma200 > 0 else 0.0)

    factors["roc5"]  = (1.2, _clamp(roc5 / 3))
    factors["roc10"] = (1.0, _clamp(roc10 / 5))
    factors["roc21"] = (1.5, _clamp(roc21 / 8))
    factors["roc63"] = (1.0, _clamp(roc63 / 15))

    rsi_score = _clamp((50 - rsi_v) / 30)
    factors["rsi14"]      = (2.0, rsi_score)
    factors["rsi_multi"]  = (1.0, _clamp((rsi_7 + rsi_21 - 100) / -60))

    macd_norm  = _clamp(macd_hist / (cur * 0.005)) if cur > 0 else 0.0
    macd_accel = _clamp((macd_hist - macd_hist_prev) / (cur * 0.002)) if cur > 0 else 0.0
    factors["macd_hist"]  = (2.0, macd_norm)
    factors["macd_accel"] = (1.0, macd_accel)

    bb_score = _clamp((0.5 - pct_b) * 2)
    factors["bollinger"]  = (1.8, bb_score)
    squeeze_bonus = 0.3 * np.sign(macd_hist) if squeeze else 0.0
    factors["bb_squeeze"] = (0.8, _clamp(squeeze_bonus))

    if has_volume:
        factors["obv_trend"]   = (1.2, obv_trend)
        factors["vwap"]        = (1.0, vwap_score)
        factors["vol_confirm"] = (1.0, vol_confirm)

    factors["ichi_pos"]    = (1.5, ichi_pos)
    factors["tk_cross"]    = (1.2, tk_cross)
    factors["cloud_color"] = (0.8, cloud_bull * 0.5)

    factors["di_score"]    = (1.5, di_score)
    factors["trend_str"]   = (0.8, trend_strength * np.sign(di_diff))

    factors["range_pos"]   = (1.0, _clamp((0.5 - range_pos) * 1.5))
    factors["divergence"]  = (2.0, div_score)

    # --- Kalman Filter adaptive trend ---
    # Simple 1D Kalman filter: estimates hidden price level + velocity
    # Superior to MA crossovers because it adapts to noise level
    kf_state = cur  # initial state estimate
    kf_vel = 0.0    # initial velocity
    kf_P = np.array([[1.0, 0.0], [0.0, 1.0]])  # covariance
    kf_Q = np.array([[0.001, 0.0], [0.0, 0.0001]])  # process noise
    kf_R = vol21 * cur * 0.01 if vol21 > 0 else cur * 0.01  # measurement noise scaled to vol
    kf_F = np.array([[1.0, 1.0], [0.0, 1.0]])  # state transition
    kf_H = np.array([[1.0, 0.0]])  # observation matrix

    # Run filter over last 60 days
    kf_lookback = min(60, n)
    kf_prices = cl.iloc[-kf_lookback:].values.astype(float)
    for p in kf_prices:
        # Predict
        state_pred = kf_F @ np.array([kf_state, kf_vel])
        P_pred = kf_F @ kf_P @ kf_F.T + kf_Q
        # Update
        innovation = p - (kf_H @ state_pred)[0]
        S = (kf_H @ P_pred @ kf_H.T)[0, 0] + kf_R
        K = (P_pred @ kf_H.T) / S
        state_upd = state_pred + K.flatten() * innovation
        kf_P = P_pred - np.outer(K.flatten(), kf_H @ P_pred)
        kf_state, kf_vel = state_upd[0], state_upd[1]

    # Kalman velocity → trend signal
    kalman_trend = _clamp(kf_vel / (cur * 0.005)) if cur > 0 else 0.0
    # Price vs Kalman estimate → mean-reversion signal
    kalman_dev = _clamp((cur - kf_state) / (cur * 0.02)) if cur > 0 else 0.0

    factors["kalman_trend"] = (2.0, kalman_trend)
    factors["kalman_dev"]   = (1.2, kalman_dev)

    # =========================================================================
    # Adaptive regime weighting
    # =========================================================================
    high_vol = vol21 > 2.5
    mean_rev_names = {"rsi14", "rsi_multi", "bollinger", "range_pos", "divergence", "bb_squeeze", "kalman_dev"}
    trend_names    = {"ma50", "ma200", "golden_cross", "roc21", "roc63",
                      "macd_hist", "ichi_pos", "di_score", "trend_str", "kalman_trend"}

    regime_mult = {}
    for name in factors:
        if high_vol and name in mean_rev_names:
            regime_mult[name] = 1.4
        elif high_vol and name in trend_names:
            regime_mult[name] = 0.7
        elif not high_vol and name in trend_names:
            regime_mult[name] = 1.3
        elif not high_vol and name in mean_rev_names:
            regime_mult[name] = 0.8
        else:
            regime_mult[name] = 1.0

    weighted_sum = 0.0
    total_weight = 0.0
    for name, (w, v) in factors.items():
        aw = w * regime_mult[name]
        weighted_sum += aw * v
        total_weight += aw

    tscore = _clamp(weighted_sum / total_weight) if total_weight > 0 else 0.0

    # =========================================================================
    # Factor agreement for confidence
    # =========================================================================
    signs = [v for _, v in factors.values()]
    pos_count = sum(1 for s in signs if s > 0.1)
    neg_count = sum(1 for s in signs if s < -0.1)
    total_factors = len(signs)
    majority = max(pos_count, neg_count)
    agreement_ratio = majority / total_factors if total_factors > 0 else 0.5
    avg_magnitude = np.mean([abs(v) for v in signs]) if signs else 0.0

    # =========================================================================
    # Macro overlay: tech 40% + macro 25% + demand 15% + fed 10% + geo 10%
    # =========================================================================
    macro  = perp.get("pplx_macro",       0.0)
    fed    = perp.get("pplx_fed",         0.0)
    demand = perp.get("pplx_phys_demand", 0.0)
    geo    = perp.get("pplx_geo_risk",    0.0)

    comb = (tscore * 0.40
            + macro  * 0.25
            + demand * 0.15
            + fed    * 0.10
            + (geo - 0.3) * 0.10)

    # =========================================================================
    # Signal classification
    # =========================================================================
    veto  = (macro < -0.3 and tscore < 0) or rsi_v > 82 or cur < ma200 * 0.96
    force = macro < -0.6 or (cur < ma50 and cur < ma200 and ret5 < -3 and rsi_v > 65)
    if bearish_div and rsi_v > 72:
        veto = True

    if force or (comb < -0.15 and veto):
        sig, css, col = "SELL", "sell", "#ef4444"
        base_conf = 40 + agreement_ratio * 35 + avg_magnitude * 20
    elif not veto and comb > 0.12:
        sig, css, col = "BUY", "buy", "#22c55e"
        base_conf = 40 + agreement_ratio * 35 + avg_magnitude * 20
    else:
        sig, css, col = "HOLD", "hold", "#f59e0b"
        base_conf = 35 + (1 - agreement_ratio) * 20 + avg_magnitude * 15

    adx_boost = min(5, (adx - 25) * 0.5) if adx > 25 and sig != "HOLD" else 0

    # MTF confluence overlay: boost/penalize confidence based on timeframe alignment
    mtf_boost = 0
    try:
        _mtf_path = Path(__file__).parent.parent / "data" / "mtf_confluence.json"
        if _mtf_path.exists():
            _mtf_data = json.loads(_mtf_path.read_text())
            _mtf_level = _mtf_data.get("confluence", {}).get("level", "")
            if sig == "BUY" and "BULLISH" in _mtf_level:
                mtf_boost = 8 if "STRONG" in _mtf_level else 4
            elif sig == "SELL" and "BEARISH" in _mtf_level:
                mtf_boost = 8 if "STRONG" in _mtf_level else 4
            elif sig == "BUY" and "BEARISH" in _mtf_level:
                mtf_boost = -6
            elif sig == "SELL" and "BULLISH" in _mtf_level:
                mtf_boost = -6
    except Exception:
        pass

    conf = int(min(94, max(25, base_conf + adx_boost + mtf_boost)))

    return dict(signal=sig, css=css, conf=conf, color=col,
                cur=cur, ma50=ma50, ma200=ma200, rsi_val=rsi_v,
                ret1=ret1, ret5=ret5, ret21=ret21, ret63=ret63,
                vol21=vol21, combined=comb, hi52=hi52, lo52=lo52)

