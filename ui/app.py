def _derive_tag(mandate: str) -> str:
    """Return 'EXTRA LONG-TERM', 'LONG-TERM', 'SWING', or 'SHORT-TERM' from strategy_mandate."""
    m = mandate.lower()
    if any(w in m for w in ("extra long", "generational", "permanent", "decade", "multi-year")):
        return "EXTRA LONG-TERM"
    if any(w in m for w in ("long", "hold", "accumul", "structural", "physical")):
        return "LONG-TERM"
    if any(w in m for w in ("swing", "rebuy", "active", "strategic exit")):
        return "SWING"
    return "SHORT-TERM"


