# ── Daily Telegram fallback flag ───────────────────────────────────────────────
# If launchd didn't fire today, the first time the dashboard loads it sends the
# morning briefing automatically. Fires at most once per calendar day.
_DAILY_FLAG_FILE = ROOT / "data" / "daily_sent.json"

def _daily_flag_sent_today() -> bool:
    try:
        data = json.loads(_DAILY_FLAG_FILE.read_text())
        return data.get("date") == date.today().isoformat()
    except Exception:
        return False

def _mark_daily_flag_sent():
    _DAILY_FLAG_FILE.parent.mkdir(parents=True, exist_ok=True)
    _DAILY_FLAG_FILE.write_text(json.dumps({"date": date.today().isoformat()}))

def _run_booter_background():
    try:
        subprocess.run(
            [sys.executable, str(ROOT / "scripts" / "daily_booter.py")],
            capture_output=True, cwd=str(ROOT)
        )
    except Exception:
        pass

def maybe_fire_daily_briefing():
    """Called once per app load. Fires booter in background if not already sent today."""
    if not _daily_flag_sent_today():
        _mark_daily_flag_sent()   # mark first to prevent double-fire on rapid reloads
        threading.Thread(target=_run_booter_background, daemon=True).start()

