def build_chart(df, accent, label, price_scale=1.0, tick_sym=""):
    if df.empty:
        fig = go.Figure()
        fig.add_annotation(text="No data available", x=0.5, y=0.5,
                           xref="paper", yref="paper", showarrow=False,
                           font=dict(size=16, color="#444"))
        fig.update_layout(paper_bgcolor="#111", plot_bgcolor="#111",
                          font=dict(color="#444"), height=420)
        return fig

    cl    = df["Close"] * price_scale
    ma50  = cl.rolling(50).mean()
    ma200 = cl.rolling(200).mean()
    bb_ma = cl.rolling(20).mean()
    bb_sd = cl.rolling(20).std()
    r, g, b = int(accent[1:3], 16), int(accent[3:5], 16), int(accent[5:7], 16)

    mean_price = float(cl.dropna().mean()) if not cl.dropna().empty else 1.0
    tick_fmt   = ",.0f" if mean_price >= 10 else ",.3f"

    fig = go.Figure()

    # Bollinger band fill
    bb_fill_color = "rgba(" + str(r) + "," + str(g) + "," + str(b) + ",0.06)"
    fig.add_trace(go.Scatter(x=df.index, y=bb_ma + 2 * bb_sd,
        line=dict(width=0), showlegend=False))
    fig.add_trace(go.Scatter(x=df.index, y=bb_ma - 2 * bb_sd,
        fill="tonexty", fillcolor=bb_fill_color,
        line=dict(width=0), showlegend=False))

    # Candles or line fallback
    if all(c in df.columns for c in ["Open", "High", "Low"]):
        fig.add_trace(go.Candlestick(
            x=df.index,
            open=df["Open"] * price_scale,
            high=df["High"] * price_scale,
            low=df["Low"]  * price_scale,
            close=cl, name=label,
            increasing_line_color="#22c55e", decreasing_line_color="#ef4444",
            increasing_fillcolor="rgba(34,197,94,0.22)",
            decreasing_fillcolor="rgba(239,68,68,0.22)",
            line=dict(width=1),
        ))
    else:
        fig.add_trace(go.Scatter(x=df.index, y=cl, name=label,
            line=dict(color=accent, width=1.6)))

    ma50_color = "rgba(" + str(r) + "," + str(g) + "," + str(b) + ",0.5)"
    fig.add_trace(go.Scatter(x=cl.index, y=ma50, name="MA-50",
        line=dict(color=ma50_color, width=1.2, dash="dot")))
    fig.add_trace(go.Scatter(x=cl.index, y=ma200, name="MA-200",
        line=dict(color=accent, width=1.6)))

    fig.update_layout(
        paper_bgcolor="#111111", plot_bgcolor="#111111",
        font=dict(family="Space Mono, monospace", color="#5a5a5a", size=10),
        legend=dict(orientation="h", y=1.02, x=0, bgcolor="rgba(0,0,0,0)",
                    font=dict(size=9), tracegroupgap=8),
        margin=dict(l=4, r=4, t=28, b=4),
        xaxis_rangeslider_visible=False,
        xaxis=dict(showgrid=False, zeroline=False, color="#2a2a2a",
                   tickfont=dict(size=9)),
        yaxis=dict(showgrid=True, gridcolor="#1a1a1a", zeroline=False,
                   color="#5a5a5a", tickfont=dict(size=9), side="right",
                   tickprefix=tick_sym, tickformat=tick_fmt),
        height=460,
    )
    return fig


