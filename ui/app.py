def score_bar(label, val, lo=-1, hi=1, val_display=None):
    """
    Center-origin bar. 0 is always the midpoint of the track.
    Green fills rightward for positive values, red fills leftward for negative.
    val_display: number shown in the label (defaults to val).
    """
    display = val if val_display is None else val_display
    span = hi - lo
    pct  = max(0, min(100, (val - lo) / span * 100))
    mid  = max(0, min(100, (0  - lo) / span * 100))
    if val >= 0:
        l = "{:.1f}%".format(mid)
        w = "{:.1f}%".format(max(0, pct - mid))
        c = "#22c55e"
    else:
        l = "{:.1f}%".format(pct)
        w = "{:.1f}%".format(max(0, mid - pct))
        c = "#ef4444"
    return (
        '<div class="srow">'
        '<div class="slbl">' + label + '</div>'
        '<div class="strack"><div class="sfill" style="left:' + l + ';width:' + w + ';background:' + c + '"></div></div>'
        '<div class="snum" style="color:' + c + '">' + "{:+.2f}".format(display) + '</div>'
        '</div>'
    )

def fmt_ret(val):
    c = "#22c55e" if val >= 0 else "#ef4444"
    s = "+" if val >= 0 else ""
    return '<span style="color:' + c + ";font-family:'Space Mono',monospace;font-size:11px\">" + s + "{:.2f}".format(val) + '%</span>'


