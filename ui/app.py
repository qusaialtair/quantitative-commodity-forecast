def analyst_call(system_prompt: str, user_message: str) -> str:
    """
    Calls Gemini with the full conversation history.
    Tries models in order until one succeeds (handles per-model quota exhaustion).
    """
    base = _analyst_base_context()
    full_system = system_prompt + ("\n\n" + base if base else "")

    history = st.session_state.get("chat_history", [])
    contents = []
    for msg in history[:-1]:
        contents.append({
            "role": msg["role"],   # "user" or "model" — Gemini convention
            "parts": [{"text": msg["content"]}],
        })
    contents.append({"role": "user", "parts": [{"text": user_message}]})

    last_err = ""
    for model in _ANALYST_MODELS:
        try:
            resp = _gemini_client().models.generate_content(
                model=model,
                contents=contents,
                config=genai_types.GenerateContentConfig(
                    system_instruction=full_system,
                    max_output_tokens=1024,
                    temperature=0.3,
                ),
            )
            try:
                return resp.text
            except ValueError:
                return "Response filtered by safety policy — try rephrasing your question."
        except Exception as exc:
            last_err = str(exc)
            continue

    # All models exhausted — inform user clearly
    if "quota" in last_err.lower() or "429" in last_err:
        return (
            "Analyst quota exhausted for today. "
            "To restore: get a free key at **aistudio.google.com** and set `GEMINI_API_KEY` in your `.env`. "
            "Alternatively, add credits to the Anthropic account and the system will auto-switch."
        )
    return "Analyst unavailable: " + last_err


def md_to_html(text: str) -> str:
    """Safe markdown → HTML: escape raw <>, strip [n] citations, bold, newlines."""
    text = re.sub(r'\[\d+\]', '', text)                          # strip citation markers
    text = text.replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;')  # escape raw HTML
    text = re.sub(r'\*\*(.+?)\*\*', r'<strong>\1</strong>', text, flags=re.DOTALL)
    text = text.replace('\n\n', '</p><p>').replace('\n', '<br>')  # paragraph + line breaks
    return f'<p style="margin:0 0 .5rem 0">{text}</p>'


def _summary_cache_key(lang: str) -> str:
    return f"summary_{lang}_{date.today().strftime('%Y%m%d')}"


def _read_summary_cache(lang: str):
    """Returns (text, sources) from file cache if current 6h bucket exists, else None."""
    path = SUMMARY_CACHE_DIR / (_summary_cache_key(lang) + ".json")
    if path.exists():
        try:
            data = json.loads(path.read_text())
            return data.get("text", ""), data.get("sources", [])
        except Exception:
            pass
    return None


def _write_summary_cache(lang: str, text: str, sources: list):
    """Write to file cache and clean up files from previous days."""
    today = date.today().strftime("%Y%m%d")
    # Delete files that don't belong to today
    for old in SUMMARY_CACHE_DIR.glob("summary_*.json"):
        if today not in old.name:
            try:
                old.unlink()
            except Exception:
                pass
    path = SUMMARY_CACHE_DIR / (_summary_cache_key(lang) + ".json")
    path.write_text(json.dumps({"text": text, "sources": sources}))


def get_market_summary(lang):
    """
    Live market summary across all 6 metals.
    Returns (text: str, sources: list[str]).
    File-based 6h cache — survives server restarts, cleaned up daily.
    """
    import requests as _req

    # -- Check file cache first --
    cached = _read_summary_cache(lang)
    if cached is not None:
        return cached  # (text, sources)

    # -- Fetch from Perplexity Sonar Pro --
    try:
        lang_instr = "Write in Arabic." if lang == "ar" else "Write in English."
        system = (
            "You are a senior commodities analyst. "
            "Return a single, well-written paragraph (4-6 sentences) summarising the current "
            "state of the global metals market \u2014 covering precious metals (gold, silver, platinum), "
            "industrial metals (copper, iron ore), and battery metals (lithium). "
            "Focus on the dominant macro themes driving prices: Fed policy, dollar strength, "
            "China demand, geopolitical risk, energy transition. Be specific with recent data where possible. "
            "No bullet points, no hedging disclaimers. Just the paragraph. " + lang_instr
        )
        user_msg = (
            "What is the current state of the global metals market as of today? "
            "Summarise the key price drivers across gold, silver, copper, lithium, platinum, and iron ore "
            "in one cohesive paragraph for a professional investor audience."
        )
        headers = {
            "Authorization": "Bearer " + PERPLEXITY_KEY,
            "Content-Type":  "application/json",
        }
        payload = {
            "model": "sonar-pro",
            "messages": [
                {"role": "system", "content": system},
                {"role": "user",   "content": user_msg},
            ],
            "temperature": 0.2,
            "max_tokens":  400,
        }
        resp = _req.post(
            "https://api.perplexity.ai/chat/completions",
            headers=headers, json=payload, timeout=20
        )
        resp.raise_for_status()
        data    = resp.json()
        text    = data["choices"][0]["message"]["content"].strip()
        sources = data.get("citations", [])
        _write_summary_cache(lang, text, sources)
        return text, sources
    except Exception:
        pass

    # -- Gemini fallback (no citations) — try all available models --
    lang_instr = "Write in Arabic." if lang == "ar" else "Write in English."
    fallback_prompt = (
        "Write a single professional paragraph (4-6 sentences) summarising the current "
        "global metals market. Cover gold, silver, copper, lithium, platinum, and iron ore. "
        "Focus on macro themes: Fed policy, dollar, China demand, geopolitics, energy transition. "
        "Be specific. No bullet points, no disclaimers. " + lang_instr
    )
    for model in _ANALYST_MODELS:
        try:
            resp = _gemini_client().models.generate_content(
                model=model,
                contents=[{"role": "user", "parts": [{"text": fallback_prompt}]}],
            )
            try:
                text = resp.text.strip()
            except ValueError:
                continue
            _write_summary_cache(lang, text, [])
            return text, []
        except Exception:
            continue
    return "Market summary unavailable — API quota exhausted. Perplexity data above is still live.", []


